"""
Resolve XDK library hooks for one title by symbol name, never by address.

    py -3 -m tools.xdk_hooks --names map_names.json --functions functions.json \
        --analysis default_analysis.json --enable d3d_block_on_time,d3d_vblank \
        --out-dir <game>/src/generated

--names: {"0xVA": "mangled name"} (tools.symbols.map_names resolve, or a MAP
via the game's seeds script). Every enabled hook must resolve to exactly one
function start in an allowed section, or this fails: a missing symbol (XDK
version without it -> add the variant to catalogue.json), a duplicate (two
addresses claim the name), a VA that tools.disasm never saw as a function, or
the wrong section.

Writes xdk_hooks_glue.c: for each hook, `void sub_X(void)` calling the
runtime's `xdk_hook_<id>(sub_X_gen, va)` (va: the
function's address in this title, for hooks that read the code itself). Pass it to tools.recomp with
--exclude-manual recomp_manual.c,xdk_hooks_glue.c so the generated body is
renamed sub_X_gen, and compile it with the game. The hook bodies live in the
runtime (src/kernel/xdk_hooks.c); a game that enables none gets no glue.
"""
import argparse, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))


def main(argv=None):
    ap = argparse.ArgumentParser(prog="tools.xdk_hooks", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--names", required=True)
    ap.add_argument("--functions", required=True)
    ap.add_argument("--analysis", required=True)
    ap.add_argument("--enable", default="", help="comma-separated hook ids ('all' = every resolvable one)")
    ap.add_argument("--catalogue", default=os.path.join(HERE, "catalogue.json"))
    ap.add_argument("--out-dir", required=True)
    a = ap.parse_args(argv)

    cat = {k: v for k, v in json.load(open(a.catalogue)).items() if not k.startswith("_")}
    names = json.load(open(a.names))
    by_name = {}
    for va, n in names.items():
        by_name.setdefault(n, set()).add(int(va, 16))
    starts = {int(f["start"], 16) for f in json.load(open(a.functions))}
    secs = [(s["name"], int(s["virtual_addr"], 16), int(s["virtual_addr"], 16) + s["virtual_size"])
            for s in json.load(open(a.analysis))["sections"]]

    def section(va):
        return next((n for n, lo, hi in secs if lo <= va < hi), "?")

    enable = [h for h in a.enable.split(",") if h]
    if enable == ["all"]:
        enable = list(cat)
    errors, resolved = [], {}
    for hid in enable:
        if hid not in cat:
            errors.append(f"{hid}: not in the catalogue")
            continue
        vas = set().union(*(by_name.get(n, set()) for n in cat[hid]["names"]))
        if not vas:
            errors.append(f"{hid}: no symbol {cat[hid]['names']} in this title")
        elif len(vas) > 1:
            errors.append(f"{hid}: duplicate, {sorted(hex(v) for v in vas)}")
        else:
            va = vas.pop()
            if va not in starts:
                errors.append(f"{hid}: {va:#010x} is not a function start in functions.json")
            elif section(va) not in cat[hid]["section"]:
                errors.append(f"{hid}: {va:#010x} in section {section(va)}, expected {cat[hid]['section']}")
            else:
                resolved[hid] = va
    for hid, va in resolved.items():
        print(f"  {hid:28s} {va:#010x}  ({section(va)})")
    if errors:
        for e in errors:
            print("error:", e, file=sys.stderr)
        return 1

    os.makedirs(a.out_dir, exist_ok=True)
    with open(os.path.join(a.out_dir, "xdk_hooks_glue.c"), "w", newline="\n") as f:
        f.write("/* Generated by tools.xdk_hooks -- do not edit. XDK hooks resolved by\n"
                " * symbol name; bodies in the runtime's xdk_hooks.c. */\n"
                "#include <stdint.h>\n"
                "typedef void (*xdk_fn)(void);\n")
        for hid, va in sorted(resolved.items(), key=lambda kv: kv[1]):
            f.write(f"\nextern void sub_{va:08X}_gen(void);\n"
                    f"extern void xdk_hook_{hid}(xdk_fn orig, uint32_t va);\n"
                    f"void sub_{va:08X}(void)\n{{\n    xdk_hook_{hid}(sub_{va:08X}_gen, 0x{va:08X}u);\n}}\n")
    json.dump({h: f"{v:#010x}" for h, v in resolved.items()},
              open(os.path.join(a.out_dir, "xdk_hooks.json"), "w"), indent=1)
    print(f"{len(resolved)} hooks -> {a.out_dir}/xdk_hooks_glue.c")
    return 0


if __name__ == "__main__":
    sys.exit(main())
